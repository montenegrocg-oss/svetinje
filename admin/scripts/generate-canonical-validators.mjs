import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fingerprintCanonicalSchemas, fingerprintRouteSchemas } from "../src/schema-fingerprint.ts";

const schemaUrls = {
  common: new URL("../../schemas/common.schema.json", import.meta.url),
  media: new URL("../../schemas/media.schema.json", import.meta.url),
  place: new URL("../../schemas/place.schema.json", import.meta.url),
  narrative: new URL("../../schemas/narrative.schema.json", import.meta.url),
  feastRegistry: new URL("../../schemas/feast-registry.schema.json", import.meta.url),
  route: new URL("../../schemas/route.schema.json", import.meta.url),
  routeNarrative: new URL("../../schemas/route-narrative.schema.json", import.meta.url),
};
const schemas = Object.fromEntries(await Promise.all(
  Object.entries(schemaUrls).map(async ([name, url]) => [name, JSON.parse(await readFile(url, "utf8"))]),
));

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  strictRequired: false,
  code: { source: true, esm: true, lines: true },
});
addFormats(ajv);
ajv.addSchema(schemas.common);
ajv.addSchema(schemas.media);
ajv.addSchema(schemas.place);
ajv.addSchema(schemas.narrative);
ajv.addSchema(schemas.feastRegistry);
ajv.addSchema(schemas.route);
ajv.addSchema(schemas.routeNarrative);

const standaloneValidators = standaloneCode(ajv, {
  validateMedia: schemas.media.$id,
  validatePlace: schemas.place.$id,
  validateNarrative: schemas.narrative.$id,
  validateFeastRegistry: schemas.feastRegistry.$id,
  validateRoute: schemas.route.$id,
  validateRouteNarrative: schemas.routeNarrative.$id,
});
const validators = standaloneValidators
  .replace(
    /^const (\w+) = require\("ajv\/dist\/runtime\/(\w+)"\)\.default;$/gm,
    (_line, name, moduleName) => `import * as ${name}Module from "ajv/dist/runtime/${moduleName}.js";\nconst ${name} = ${name}Module.default?.default ?? ${name}Module.default;`,
  )
  .replace(
    /^const (\w+) = require\("ajv-formats\/dist\/formats"\)\.fullFormats(\[[^;]+\]|\.\w+);$/gm,
    (_line, name, accessor) => `import * as ${name}Module from "ajv-formats/dist/formats.js";\nconst ${name} = (${name}Module.fullFormats ?? ${name}Module.default?.fullFormats)${accessor};`,
  );
if (/\brequire\s*\(/.test(validators)) {
  throw new Error("Generated standalone validators contain an unsupported CommonJS runtime import");
}
const fingerprint = await fingerprintCanonicalSchemas(schemas);
const routeFingerprint = await fingerprintRouteSchemas(schemas);
const output = `/* Generated by scripts/generate-canonical-validators.mjs. Do not edit. */\n${validators}\nexport const CANONICAL_SCHEMA_FINGERPRINT = ${JSON.stringify(fingerprint)};\nexport const ROUTE_SCHEMA_FINGERPRINT = ${JSON.stringify(routeFingerprint)};\n`;
const outputUrl = new URL("../src/generated/canonical-validators.js", import.meta.url);
const declarationsUrl = new URL("../src/generated/canonical-validators.d.ts", import.meta.url);
await mkdir(new URL("../src/generated/", import.meta.url), { recursive: true });
await writeFile(outputUrl, output, "utf8");
await writeFile(declarationsUrl, `import type { ValidateFunction } from "ajv";\nexport const validateMedia: ValidateFunction;\nexport const validatePlace: ValidateFunction;\nexport const validateNarrative: ValidateFunction;\nexport const validateFeastRegistry: ValidateFunction;\nexport const validateRoute: ValidateFunction;\nexport const validateRouteNarrative: ValidateFunction;\nexport const CANONICAL_SCHEMA_FINGERPRINT: string;\nexport const ROUTE_SCHEMA_FINGERPRINT: string;\n`, "utf8");
